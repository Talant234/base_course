
a = int(input("Введите первое число (делимое): "))
b = int(input("Введите второе число (делитель): "))

if b == 0:
    print("Ошибка: деление на ноль!")
else:
    q = a / b
    r = a % b
    
    print(f"Частное: {q}")
    
    if r == 0:
        print(f"Число {a} делится на число {b} без остатка")
    else:
        print(f"Число {a} НЕ делится на число {b} без остатка")
        print(f"Остаток от деления: {r}")
